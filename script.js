
const farmForm = document.getElementById("farmForm");

const getValue = (id) => {
  return Number(document.getElementById(id).value);
};

farmForm.addEventListener("submit", function (event) {
  event.preventDefault();

  // Read the values entered by the user.
  const moisture = getValue("moisture");
  const temperature = getValue("temperature");
  const humidity = getValue("humidity");
  const nitrogen = getValue("nitrogen");
  const phosphorus = getValue("phosphorus");
  const potassium = getValue("potassium");
  const ph = getValue("ph");
  const rainfall = getValue("rainfall");

  // These are indicative reference ranges for this demo.
  // Confirm suitable ranges and units for your actual dataset.
  const checks = [
    {
      name: "Soil moisture",
      isGood: moisture >= 55 && moisture <= 75
    },
    {
      name: "Temperature",
      isGood: temperature >= 25 && temperature <= 32
    },
    {
      name: "Humidity",
      isGood: humidity >= 60 && humidity <= 75
    },
    {
      name: "Soil pH",
      isGood: ph >= 5.5 && ph <= 7.0
    },
    {
      name: "Rainfall",
      isGood: rainfall >= 150 && rainfall <= 300
    }
  ];

  // DEMONSTRATION ONLY:
  // This score is not calculated by the trained XGBoost model.
  let demoScore = 35;

  if (moisture >= 55 && moisture <= 75) demoScore += 3;
  if (temperature >= 25 && temperature <= 32) demoScore += 3;
  if (humidity >= 60 && humidity <= 75) demoScore += 2;
  if (ph >= 5.5 && ph <= 7.0) demoScore += 2;
  if (rainfall >= 150 && rainfall <= 300) demoScore += 2;

  if (nitrogen > 0 && phosphorus > 0 && potassium > 0) {
    demoScore += 1;
  }

  // Update the demonstration result.
  document.getElementById("yieldValue").textContent = demoScore;

  document.getElementById("resultNote").textContent =
    "Demo score only. This value is generated by placeholder rules, " +
    "not by the trained XGBoost model.";

  // Count the readings inside the displayed reference ranges.
  const suitableCount = checks.filter(
    (item) => item.isGood
  ).length;

  document.getElementById("climateNote").textContent =
    `${suitableCount} out of ${checks.length} readings are within ` +
    "the displayed reference ranges. These ranges are indicative " +
    "and should be validated for your local growing conditions.";
});
